#!/usr/bin/env node
// Generates .ai/INDEX.md: a compact symbol map of src/ for AI assistants.
// Lets a model find the right file from one small file instead of opening everything.
//   node scripts/context-map.mjs          -> write the index
//   node scripts/context-map.mjs --check  -> exit 1 if the index is stale (used in CI)
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const OUT = join(ROOT, '.ai', 'INDEX.md');

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) return walk(path);
    return /\.(ts|tsx)$/.test(entry.name) ? [path] : [];
  });
}

const EXPORT_RE =
  /^export\s+(?:default\s+)?(?:async\s+)?(function|const|interface|type|class)\s+([A-Za-z0-9_]+)/gm;
const TEST_RE = /^\s*it(?:\.each\([\s\S]*?\))?\(\s*['"`]/gm;

function describe(file) {
  const src = readFileSync(file, 'utf8');
  return {
    exports: [...src.matchAll(EXPORT_RE)].map((m) => `\`${m[2]}\` (${m[1]})`),
    tests: [...src.matchAll(TEST_RE)].length,
    lines: src.split('\n').length,
  };
}

// Posix-style paths so the output is identical on every OS (CI check depends on it).
const toPosix = (p) => p.split('\\').join('/');

const files = walk(join(ROOT, 'src')).sort();
const rows = files.map((file) => {
  const rel = toPosix(relative(ROOT, file));
  const { exports, tests, lines } = describe(file);
  const what = rel.includes('.test.') ? `${tests} test cases` : exports.join(', ') || '—';
  return `| \`${rel}\` | ${lines} | ${what} |`;
});

const content = `<!-- Generated by scripts/context-map.mjs. Do not edit by hand: run \`npm run context\`. -->
# Source index

Read this to locate code before opening files. Area rules live in the \`AGENTS.md\` of each folder.

| File | Lines | Exports / contents |
| --- | ---: | --- |
${rows.join('\n')}
`;

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== content) {
    console.error('.ai/INDEX.md is stale. Run `npm run context` and commit the result.');
    process.exit(1);
  }
  console.log('.ai/INDEX.md is up to date.');
} else {
  writeFileSync(OUT, content);
  console.log(`Wrote .ai/INDEX.md (${files.length} files).`);
}
